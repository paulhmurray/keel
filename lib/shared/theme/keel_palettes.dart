import 'package:flutter/material.dart';

/// A complete colour set for the UI. Role names are historical: `amber`
/// is the primary accent, `phosphor` the positive one, `red` the alarm,
/// `blue` and `violet` the two secondary hues; the `*Dim` variants are
/// their tinted backgrounds. [onAccent] is text on a primary or positive
/// fill. Exports never use these — they are styled for print.
class KeelPalette {
  final String id;
  final String name;
  final Brightness brightness;
  final Color bg, surface, surface2, border, border2;
  final Color amber, amberDim, phosphor, phosDim, red, redDim;
  final Color blue, blueDim, violet, violetDim;
  final Color text, textDim, textMuted;
  final Color onAccent;

  const KeelPalette({
    required this.id,
    required this.name,
    required this.brightness,
    required this.bg,
    required this.surface,
    required this.surface2,
    required this.border,
    required this.border2,
    required this.amber,
    required this.amberDim,
    required this.phosphor,
    required this.phosDim,
    required this.red,
    required this.redDim,
    required this.blue,
    required this.blueDim,
    required this.violet,
    required this.violetDim,
    required this.text,
    required this.textDim,
    required this.textMuted,
    required this.onAccent,
  });

  bool get isLight => brightness == Brightness.light;

  /// Every role, for tests and swatches.
  List<Color> get roles => [
    bg,
    surface,
    surface2,
    border,
    border2,
    amber,
    amberDim,
    phosphor,
    phosDim,
    red,
    redDim,
    blue,
    blueDim,
    violet,
    violetDim,
    text,
    textDim,
    textMuted,
    onAccent,
  ];
}

